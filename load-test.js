import http from 'k6/http';
import { sleep, check } from 'k6';

// ==============================================================================
// 📊 CONFIGURATION: การตั้งค่าโหลดทดสอบ (Load Test Settings)
// ==============================================================================
export const options = {
  stages: [
    { duration: '1m', target: 200 }, // 1. ค่อยๆ เพิ่มผู้ใช้งานจาก 0 ไปถึง 200 คนในเวลา 1 นาที (Ramp-up)
    { duration: '2m', target: 200 }, // 2. รักษาระดับผู้ใช้งานไว้ที่ 200 คนค้างไว้เป็นเวลา 2 นาที (Hold / Peak Load)
    { duration: '30s', target: 0 },  // 3. ค่อยๆ ลดจำนวนผู้ใช้งานลงจนเหลือ 0 ในเวลา 30 วินาที (Ramp-down)
  ],
  thresholds: {
    http_req_failed: ['rate<0.01'],   // เป้าหมาย: อัตราคำขอที่ล้มเหลว (Error) ต้องน้อยกว่า 1%
    http_req_duration: ['p(95)<2000'], // เป้าหมาย: 95% ของความเร็วในการตอบสนองต้องน้อยกว่า 2 วินาที (2000ms)
  },
};

// ==============================================================================
// 🌐 TARGET URL: กรุณาเปลี่ยนเป็น URL เว็บไซต์จริง หรือ URL ท้องถิ่นของคุณ
// ==============================================================================
// ตัวอย่างรันในเครื่องตัวเอง: 'http://localhost:5173'
// ตัวอย่างรันบนเว็บบนโฮสต์จริง: 'https://candy-v3.vercel.app'
const TARGET_URL = 'https://candy-fawn-chi.vercel.app';

// ==============================================================================
// 🏃 VIRTUAL USER BEHAVIOR: จำลองพฤติกรรมของน้องๆ/ผู้ใช้แต่ละคน
// ==============================================================================
export default function () {
  // 1. จำลองการเปิดหน้าแรก (Leaderboard หรือ Dashboard)
  const res = http.get(`${TARGET_URL}/`);
  
  // ตรวจสอบว่าเปิดเว็บสำเร็จหรือไม่ (HTTP Status 200)
  check(res, {
    'status is 200': (r) => r.status === 200,
    'body is not empty': (r) => r.body && r.body.length > 0,
  });

  // 2. จำลองว่าน้องๆ นั่งจ้องหน้าจอคะแนนแล้วรอ 1 ถึง 3 วินาทีก่อนที่จะดูความเคลื่อนไหวต่อ
  // การหน่วงเวลานี้สำคัญมาก เพราะทำให้พฤติกรรมใกล้เคียงมนุษย์จริงๆ ไม่ใช่ยิงถล่มแบบสแปมบอท
  sleep(Math.random() * 2 + 1); 
}
